#define DSTU9212_PK_OCTETS_COMPUTED \
    (DSTU9212_SEED_OCTETS + \
     DSTU9212_OCTETS(DSTU9212_K * DSTU9212_N * (DSTU9212_Q_BITS - DSTU9212_D)))

#define DSTU9212_SK_OCTETS_COMPUTED \
    (2 * DSTU9212_SEED_OCTETS + DSTU9212_HASH_OCTETS + \
     DSTU9212_OCTETS(DSTU9212_N * \
                     ((DSTU9212_L + DSTU9212_K) * DSTU9212_LOG2_2ETA + \
                      DSTU9212_K * DSTU9212_D)))

#define DSTU9212_HINT_OCTETS \
    (DSTU9212_N == 256 ? (DSTU9212_OMEGA + DSTU9212_K) \
                       : (DSTU9212_OMEGA + 4 * DSTU9212_K))

#define DSTU9212_DS_OCTETS_COMPUTED \
    (DSTU9212_SEED_OCTETS + \
     DSTU9212_OCTETS(DSTU9212_LOG2_Z * DSTU9212_N * DSTU9212_L) + \
     DSTU9212_HINT_OCTETS)

